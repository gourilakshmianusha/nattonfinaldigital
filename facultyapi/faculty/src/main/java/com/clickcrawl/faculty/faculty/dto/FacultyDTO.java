package com.clickcrawl.faculty.faculty.dto;

public class FacultyDTO {

    private String firstName;
    private String lastName;
    private Integer age;
    private String gender;
    private String email;
    private String contact;
    private String address;
    private String city;
    private String pincode;
    private String qualification;
    private String classYouTeach;
    private String subjectsYouTeach;
    private String experienceOfTeaching;
    private String previousExperiences;
    private String photo; // URL string

    // Getters and setters

    public String getFirstName() {
        return firstName;
    }
    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }
    public String getLastName() {
        return lastName;
    }
    public void setLastName(String lastName) {
        this.lastName = lastName;
    }
    public Integer getAge() {
        return age;
    }
    public void setAge(Integer age) {
        this.age = age;
    }
    public String getGender() {
        return gender;
    }
    public void setGender(String gender) {
        this.gender = gender;
    }
    public String getEmail() {
        return email;
    }
    public void setEmail(String email) {
        this.email = email;
    }
    public String getContact() {
        return contact;
    }
    public void setContact(String contact) {
        this.contact = contact;
    }
    public String getAddress() {
        return address;
    }
    public void setAddress(String address) {
        this.address = address;
    }
    public String getCity() {
        return city;
    }
    public void setCity(String city) {
        this.city = city;
    }
    public String getPincode() {
        return pincode;
    }
    public void setPincode(String pincode) {
        this.pincode = pincode;
    }
    public String getQualification() {
        return qualification;
    }
    public void setQualification(String qualification) {
        this.qualification = qualification;
    }
    public String getClassYouTeach() {
        return classYouTeach;
    }
    public void setClassYouTeach(String classYouTeach) {
        this.classYouTeach = classYouTeach;
    }
    public String getSubjectsYouTeach() {
        return subjectsYouTeach;
    }
    public void setSubjectsYouTeach(String subjectsYouTeach) {
        this.subjectsYouTeach = subjectsYouTeach;
    }
    public String getExperienceOfTeaching() {
        return experienceOfTeaching;
    }
    public void setExperienceOfTeaching(String experienceOfTeaching) {
        this.experienceOfTeaching = experienceOfTeaching;
    }
    public String getPreviousExperiences() {
        return previousExperiences;
    }
    public void setPreviousExperiences(String previousExperiences) {
        this.previousExperiences = previousExperiences;
    }
    public String getPhoto() {
        return photo;
    }
    public void setPhoto(String photo) {
        this.photo = photo;
    }
}
